-- Verificacion de correo. Sin ella, cualquiera podia registrarse con un correo
-- ajeno y, peor, quedarse con la cuenta cuando el dueño entrara con Google.
--
-- Las cuentas que ya existen quedan verificadas: no se les puede pedir que
-- confirmen un correo que nadie les mando. Del token solo se guarda el hash.

ALTER TABLE public.users ADD COLUMN email_verified boolean;
UPDATE public.users SET email_verified = true;
ALTER TABLE public.users ALTER COLUMN email_verified SET NOT NULL;

CREATE TABLE public.email_verification_tokens (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    token_hash character varying(64) NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    used_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.email_verification_tokens ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.email_verification_tokens_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.email_verification_tokens ADD CONSTRAINT email_verification_tokens_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.email_verification_tokens ADD CONSTRAINT uk_email_verification_tokens_hash UNIQUE (token_hash);
ALTER TABLE ONLY public.email_verification_tokens
    ADD CONSTRAINT fk_email_verification_tokens_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;
CREATE INDEX idx_email_verification_tokens_user ON public.email_verification_tokens USING btree (user_id);
