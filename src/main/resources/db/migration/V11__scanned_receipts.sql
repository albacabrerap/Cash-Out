-- Boletas ya registradas, para avisar si se escanea la misma dos veces.
--
-- No se guarda la boleta: solo una huella HMAC del usuario, el RUC, el tipo, la
-- serie y el numero, con una clave que vive fuera de la base. Quien lea esta
-- tabla no puede saber que boletas tiene cada usuario. Borrar el gasto (o el
-- ingreso, si era una nota de credito) borra la huella y deja registrarla otra vez.

CREATE TABLE public.scanned_receipts (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    fingerprint character varying(64) NOT NULL,
    expense_id bigint,
    income_id bigint,
    created_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.scanned_receipts ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.scanned_receipts_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.scanned_receipts ADD CONSTRAINT scanned_receipts_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.scanned_receipts
    ADD CONSTRAINT uk_scanned_receipts_user_fingerprint UNIQUE (user_id, fingerprint);
ALTER TABLE ONLY public.scanned_receipts
    ADD CONSTRAINT fk_scanned_receipts_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;
ALTER TABLE ONLY public.scanned_receipts
    ADD CONSTRAINT fk_scanned_receipts_expense FOREIGN KEY (expense_id) REFERENCES public.expenses(id) ON DELETE CASCADE;
ALTER TABLE ONLY public.scanned_receipts
    ADD CONSTRAINT fk_scanned_receipts_income FOREIGN KEY (income_id) REFERENCES public.incomes(id) ON DELETE CASCADE;
