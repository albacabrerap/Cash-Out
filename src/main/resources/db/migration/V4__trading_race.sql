-- Carrera de trading: salas, jugadores y los movimientos de fichas que generan.
--
-- La carrera corre en memoria; aqui queda lo que tiene que sobrevivir a un
-- reinicio: quien jugo, cuanto pago, en que puesto termino y cuanto gano.

CREATE TABLE public.race_rooms (
    id bigint NOT NULL,
    code character varying(6) NOT NULL,
    host_id bigint NOT NULL,
    scenario_key character varying(40) NOT NULL,
    entry_fee numeric(19,2) NOT NULL,
    status character varying(20) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    started_at timestamp(6) without time zone,
    finished_at timestamp(6) without time zone,
    CONSTRAINT race_rooms_entry_fee_check CHECK ((entry_fee >= (0)::numeric)),
    CONSTRAINT race_rooms_status_check CHECK (((status)::text = ANY ((ARRAY['LOBBY'::character varying, 'RUNNING'::character varying, 'FINISHED'::character varying, 'CANCELLED'::character varying])::text[])))
);

ALTER TABLE public.race_rooms ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.race_rooms_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.race_rooms ADD CONSTRAINT race_rooms_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.race_rooms ADD CONSTRAINT uk_race_rooms_code UNIQUE (code);
ALTER TABLE ONLY public.race_rooms
    ADD CONSTRAINT fk_race_rooms_host FOREIGN KEY (host_id) REFERENCES public.users(id);
CREATE INDEX idx_race_rooms_status ON public.race_rooms USING btree (status);

CREATE TABLE public.race_players (
    id bigint NOT NULL,
    room_id bigint NOT NULL,
    user_id bigint NOT NULL,
    joined_at timestamp(6) without time zone NOT NULL,
    final_value numeric(19,2),
    final_rank integer,
    prize numeric(19,2) NOT NULL,
    CONSTRAINT race_players_prize_check CHECK ((prize >= (0)::numeric))
);

ALTER TABLE public.race_players ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.race_players_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.race_players ADD CONSTRAINT race_players_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.race_players ADD CONSTRAINT uk_race_players_room_user UNIQUE (room_id, user_id);
ALTER TABLE ONLY public.race_players
    ADD CONSTRAINT fk_race_players_room FOREIGN KEY (room_id) REFERENCES public.race_rooms(id);
ALTER TABLE ONLY public.race_players
    ADD CONSTRAINT fk_race_players_user FOREIGN KEY (user_id) REFERENCES public.users(id);

-- La cuota, el premio y la devolucion apuntan a la fila del jugador: el par
-- (motivo, referencia) es UNIQUE, y con la sala como referencia chocaria el
-- segundo jugador.
ALTER TABLE public.token_transactions DROP CONSTRAINT token_transactions_reason_check;
ALTER TABLE public.token_transactions ADD CONSTRAINT token_transactions_reason_check
    CHECK (((reason)::text = ANY ((ARRAY['GOAL_COMPLETED'::character varying, 'MINIGAME'::character varying, 'INVESTMENT'::character varying, 'ADJUSTMENT'::character varying, 'RACE_ENTRY'::character varying, 'RACE_PRIZE'::character varying, 'RACE_REFUND'::character varying])::text[])));
