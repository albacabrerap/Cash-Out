-- Favoritos del mercado: los activos que el usuario sigue, como la watchlist de un broker.
--
-- Un activo aparece una sola vez por usuario; borrar la cuenta o el activo borra la fila.

CREATE TABLE public.watchlist_items (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    asset_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.watchlist_items ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.watchlist_items_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.watchlist_items ADD CONSTRAINT watchlist_items_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.watchlist_items ADD CONSTRAINT uk_watchlist_user_asset UNIQUE (user_id, asset_id);
ALTER TABLE ONLY public.watchlist_items
    ADD CONSTRAINT fk_watchlist_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;
ALTER TABLE ONLY public.watchlist_items
    ADD CONSTRAINT fk_watchlist_asset FOREIGN KEY (asset_id) REFERENCES public.assets(id) ON DELETE CASCADE;
