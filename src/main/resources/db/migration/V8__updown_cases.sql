-- Banco de casos de "¿Sube o baja?". Los edita un ADMIN; cada partida toma
-- los que hace mas tiempo no salen (times_played y last_played_at).
--
-- change_percent es el resultado real del mes siguiente, calculado al guardar
-- el caso; la partida lo vuelve a calcular con los cierres que muestra.

CREATE TABLE public.updown_cases (
    id bigint NOT NULL,
    symbol character varying(12) NOT NULL,
    cutoff date NOT NULL,
    sector character varying(60) NOT NULL,
    name character varying(160) NOT NULL,
    context character varying(300) NOT NULL,
    lesson character varying(600) NOT NULL,
    change_percent numeric(7,2),
    active boolean NOT NULL,
    times_played integer NOT NULL,
    last_played_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT updown_cases_times_played_check CHECK ((times_played >= 0))
);

ALTER TABLE public.updown_cases ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.updown_cases_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.updown_cases ADD CONSTRAINT updown_cases_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.updown_cases ADD CONSTRAINT uk_updown_cases_symbol_cutoff UNIQUE (symbol, cutoff);
CREATE INDEX idx_updown_cases_active ON public.updown_cases USING btree (active);

