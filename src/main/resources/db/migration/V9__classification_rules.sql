-- Reglas de clasificacion que cada usuario crea al corregir una sugerencia:
-- "este RUC es Comida", "tottus es Comida". Le ganan a cualquier clasificador.
--
-- pattern va normalizado (minusculas, sin tildes ni signos) para comparar
-- palabras; en una regla por RUC son los 11 digitos. category es NULL en un ingreso.

CREATE TABLE public.classification_rules (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    match_type character varying(10) NOT NULL,
    pattern character varying(120) NOT NULL,
    kind character varying(10) NOT NULL,
    category character varying(30),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT classification_rules_match_type_check CHECK (((match_type)::text = ANY ((ARRAY['RUC'::character varying, 'KEYWORD'::character varying])::text[]))),
    CONSTRAINT classification_rules_kind_check CHECK (((kind)::text = ANY ((ARRAY['INCOME'::character varying, 'EXPENSE'::character varying])::text[]))),
    CONSTRAINT classification_rules_category_check CHECK (((category)::text = ANY ((ARRAY['FOOD'::character varying, 'TRANSPORT'::character varying, 'SERVICES'::character varying, 'EDUCATION'::character varying, 'LEISURE'::character varying, 'HEALTH'::character varying, 'OTHER'::character varying])::text[])))
);

ALTER TABLE public.classification_rules ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.classification_rules_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.classification_rules ADD CONSTRAINT classification_rules_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.classification_rules
    ADD CONSTRAINT uk_classification_rules_user_match UNIQUE (user_id, match_type, pattern);
ALTER TABLE ONLY public.classification_rules
    ADD CONSTRAINT fk_classification_rules_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;
